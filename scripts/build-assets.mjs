// Build the self-hosted CSS + icon assets.
//
// The Worker serves these from /assets/*. They are bundled into
// src/frontend/generated-assets.js so the panel never depends on an external
// CDN (which the strict CSP blocks, and which some mobile networks block too).
//
// Tailwind is split in two:
//   - base (preflight + components) loads before the panel's custom CSS
//   - utilities load after the custom CSS, so utilities such as `absolute`
//     and `sticky` win over component defaults like `.glass-sidebar`.
//
// Run: npm run assets:build

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const tmp = mkdtempSync(join(tmpdir(), 'panel-assets-'));

function tailwind(input, output) {
  execFileSync(process.execPath, [
    'node_modules/tailwindcss/lib/cli.js',
    '-c', 'tailwind.config.cjs',
    '-i', input,
    '-o', output,
    '--minify',
  ], { cwd: root, stdio: 'inherit' });
}

const baseOut = join(tmp, 'tailwind-base.css');
const utilitiesOut = join(tmp, 'tailwind-utilities.css');
tailwind('src/frontend/tailwind.base.css', baseOut);
tailwind('src/frontend/tailwind.utilities.css', utilitiesOut);

const baseCss = readFileSync(baseOut, 'utf8').trim();
const utilitiesCss = readFileSync(utilitiesOut, 'utf8').trim();
const iconCssRaw = readFileSync(join(root, 'vendor/bootstrap-icons/bootstrap-icons.css'), 'utf8');
const iconFont = readFileSync(join(root, 'vendor/bootstrap-icons/fonts/bootstrap-icons.woff2'));
const iconFontB64 = iconFont.toString('base64');

// Only ship the woff2 font (all supported browsers use it). The CSS shipped
// by Bootstrap Icons references a woff fallback with a cache-busting query.
const iconCss = iconCssRaw.replace(
  /src:\s*url\("?\.\/fonts\/bootstrap-icons\.woff2[^"]*"?\)\s*format\("woff2"\),\s*url\("?\.\/fonts\/bootstrap-icons\.woff[^"]*"?\)\s*format\("woff"\);/,
  'src: url("/assets/bootstrap-icons.woff2") format("woff2");',
);
if (iconCss === iconCssRaw) {
  throw new Error('bootstrap-icons.css font-face block was not rewritten');
}

const version = createHash('sha256')
  .update(baseCss)
  .update(utilitiesCss)
  .update(iconCss)
  .update(iconFontB64)
  .digest('hex')
  .slice(0, 10);

const out = `// AUTO-GENERATED by scripts/build-assets.mjs. Do not edit by hand.
// Tailwind is compiled from src/**/*.js; Bootstrap Icons is vendored under
// vendor/bootstrap-icons (MIT). Run "npm run assets:build" after changing
// classes or upgrading either asset.
export const ASSET_VERSION = ${JSON.stringify(version)};
export const TAILWIND_BASE_CSS = ${JSON.stringify(baseCss)};
export const TAILWIND_UTILITIES_CSS = ${JSON.stringify(utilitiesCss)};
export const BOOTSTRAP_ICONS_CSS = ${JSON.stringify(iconCss)};
export const BOOTSTRAP_ICONS_WOFF2_B64 = ${JSON.stringify(iconFontB64)};
`;

writeFileSync(join(root, 'src/frontend/generated-assets.js'), out);
console.log(`assets built: base ${(baseCss.length / 1024).toFixed(1)} KiB, utilities ${(utilitiesCss.length / 1024).toFixed(1)} KiB, icons ${(iconCss.length / 1024).toFixed(1)} KiB, font ${(iconFont.length / 1024).toFixed(1)} KiB, version ${version}`);
