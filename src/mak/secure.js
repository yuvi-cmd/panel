// MAK/2 envelope v3 — dual-ephemeral X25519 + HKDF-SHA256 +
// XSalsa20-Poly1305. No symmetric key is compiled into the SDK or stored in
// Worker source.
//
// Request  : { v:3, k:<panel X25519 key id>, e:<client ephemeral pub>,
//              n:<24-byte nonce>, s:<32-byte salt>, c:<cipher> }
// Response : { v:3, k:<panel Ed25519 key id>, e:<server ephemeral pub>,
//              n:<fresh 24-byte nonce>, s:<fresh 32-byte salt>,
//              c:<cipher>, sig:<Ed25519 over the canonical header> }
//
// Request key  = HKDF(X25519(client_eph, panel_static), salt,
//                     "MAK/2|REQ|3|<key_id>|<client_eph_b64>")
// Response key = HKDF(X25519(server_eph, client_eph), salt,
//                     "MAK/2|RESP|3|<client_eph>|<server_eph>|<request_nonce>")
//
// The response uses a fresh server ephemeral key for every request, so the
// response key is forward-secret and independent from the panel's long-term
// X25519 key. The Ed25519 signature covers the canonical response header
// (including the ephemeral key, nonce and ciphertext) and is verified before
// decryption. The inner response still carries its own domain signature.
//
// The panel X25519/Ed25519 keypairs are generated by the panel and stored in
// D1. The SDK pins only the Ed25519 public trust anchor; no encryption secret
// is ever distributed to clients.

import nacl from 'tweetnacl';
import {
  PROTOCOL_V2, b64decode, b64encode, canonicalJson, hkdfSha256,
  loadEncryptionConfig, loadSigningConfig, randomBytes, utf8, fromUtf8,
  secureEqualBytes,
} from './crypto.js';

const ENVELOPE_VERSION = 3;
const NONCE_BYTES = 24;
const SALT_BYTES = 32;
const MIN_CIPHER_BYTES = 16;

export const ENVELOPE_V3 = ENVELOPE_VERSION;
export const ENVELOPE_SUITE = 'MAK/2-DHE-V3';

export class EnvelopeError extends Error {
  constructor(code, message = code) {
    super(message);
    this.code = code;
  }
}

export function isEnvelope(body) {
  return !!body && typeof body === 'object'
    && Number(body.v) === ENVELOPE_VERSION
    && typeof body.k === 'string'
    && body.e && body.n && body.s && body.c;
}

function resolveKeys(input) {
  if (input && input.encryption && input.signing) return input;
  return {
    encryption: loadEncryptionConfig(input || {}),
    signing: loadSigningConfig(input || {}),
  };
}

export function requestInfo(keyId, clientPublicB64) {
  return `${PROTOCOL_V2}|REQ|${ENVELOPE_VERSION}|${keyId}|${clientPublicB64}`;
}

export function responseInfo(clientPublicB64, serverPublicB64, requestNonceB64) {
  return `${PROTOCOL_V2}|RESP|${ENVELOPE_VERSION}|${clientPublicB64}|${serverPublicB64}|${requestNonceB64}`;
}

export async function openRequest(body, keysOrEnv) {
  const keys = resolveKeys(keysOrEnv);
  const enc = keys.encryption;
  if (!enc?.ok) throw new EnvelopeError('ENCRYPTION_NOT_CONFIGURED', enc?.reason || 'encryption key is not configured');

  const keyId = String(body.k || '');
  if (!keyId || keyId !== String(enc.key_id || '')) {
    throw new EnvelopeError('ENCRYPTION_KEY_MISMATCH', 'request was sealed to a different panel key');
  }

  const clientPub = b64decode(body.e);
  const nonce = b64decode(body.n);
  const salt = b64decode(body.s);
  const cipher = b64decode(body.c);
  if (clientPub.length !== 32) throw new EnvelopeError('ENVELOPE_INVALID', 'client key must be 32 bytes');
  if (nonce.length !== NONCE_BYTES) throw new EnvelopeError('ENVELOPE_INVALID', 'nonce must be 24 bytes');
  if (salt.length !== SALT_BYTES) throw new EnvelopeError('ENVELOPE_INVALID', 'salt must be 32 bytes');
  if (cipher.length < MIN_CIPHER_BYTES) throw new EnvelopeError('ENVELOPE_INVALID', 'ciphertext is empty');

  let shared;
  try {
    shared = nacl.box.before(clientPub, enc.secret_key);
  } catch {
    throw new EnvelopeError('ENVELOPE_INVALID', 'X25519 key agreement failed');
  }
  const key = await hkdfSha256(shared, salt, requestInfo(keyId, b64encode(clientPub)));
  let plain;
  try {
    plain = nacl.secretbox.open(cipher, nonce, key);
  } catch {
    plain = null;
  }
  if (!plain) throw new EnvelopeError('ENVELOPE_INVALID', 'decrypt failed');

  let payload;
  try {
    payload = JSON.parse(fromUtf8(plain));
  } catch {
    throw new EnvelopeError('ENVELOPE_INVALID', 'payload is not JSON');
  }
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {
    throw new EnvelopeError('ENVELOPE_INVALID', 'payload must be an object');
  }
  return {
    version: ENVELOPE_VERSION,
    payload,
    shared,
    nonce,
    salt,
    clientPub,
    key_id: keyId,
  };
}

export async function sealResponse(payload, ctx, keysOrEnv) {
  const keys = resolveKeys(keysOrEnv);
  const signing = keys.signing;
  if (!signing?.ok) throw new EnvelopeError('SERVER_ERROR', 'signing key is not configured');
  if (!ctx?.clientPub || !ctx?.nonce) throw new EnvelopeError('ENVELOPE_INVALID', 'response context is missing');

  // Fresh server ephemeral key for every response. This makes the response
  // key independent from the long-term panel encryption key.
  const serverEphemeral = nacl.box.keyPair();
  let shared;
  try {
    shared = nacl.box.before(ctx.clientPub, serverEphemeral.secretKey);
  } catch {
    throw new EnvelopeError('ENVELOPE_INVALID', 'response key agreement failed');
  }
  const salt = randomBytes(SALT_BYTES);
  const nonce = randomBytes(NONCE_BYTES);
  const info = responseInfo(
    b64encode(ctx.clientPub),
    b64encode(serverEphemeral.publicKey),
    b64encode(ctx.nonce),
  );
  const key = await hkdfSha256(shared, salt, info);

  const plaintext = canonicalJson(payload);
  const cipher = nacl.secretbox(utf8(plaintext), nonce, key);
  const header = {
    v: ENVELOPE_VERSION,
    k: signing.active.key_id,
    e: b64encode(serverEphemeral.publicKey),
    n: b64encode(nonce),
    s: b64encode(salt),
    c: b64encode(cipher),
  };
  const message = `${PROTOCOL_V2}\nENVELOPE-V3\n${canonicalJson(header)}`;
  const signature = nacl.sign.detached(utf8(message), signing.active.secret_key);
  return { ...header, sig: b64encode(signature) };
}

// Constant-time check used by callers that need to compare endpoint tags.
export function sameBytes(a, b) {
  return secureEqualBytes(a, b);
}
